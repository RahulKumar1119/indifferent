#!/usr/bin/env python3
"""Writes backend/internal/shorts/render/metrics_gen.go: how wide each character is in the fonts
the render images use for captions (#327).

The renderers burn captions with libass, which takes its fonts from the image: DejaVu Sans, DejaVu
Serif and DejaVu Sans Condensed for Latin text, and Noto Sans Devanagari for Hindi (the Dockerfiles
install ttf-dejavu and font-noto-devanagari). Caption fitting needs to know how wide a line will be
before it is drawn, so it measures with these tables. Widths are in thousandths of an em, rounded up,
so an estimate is never narrower than the font's own advances.

Run it against the fonts from the same Alpine packages the images use, for example:

    scripts/ops/caption_fit_check.sh --fonts        # copies them out of alpine:3.21 into a folder
    python3 scripts/ops/gen_caption_metrics.py <folder>

The folder needs DejaVuSans.ttf, DejaVuSerif.ttf, DejaVuSansCondensed.ttf and
NotoSansDevanagari-Regular.ttf. Prints nothing but the path it wrote.
"""
import math
import pathlib
import sys

from fontTools.ttLib import TTFont

LATIN_FIRST, LATIN_LAST = 0x20, 0x17F  # Basic Latin, Latin-1 Supplement, Latin Extended-A
DEVA_FIRST, DEVA_LAST = 0x900, 0x97F
# Noto Sans Devanagari also has the space, digits and most punctuation. A caption in the default font
# ("Arial") is looked up in Noto Sans Devanagari first, because fontconfig lists it ahead of DejaVu
# for that name, so those characters are drawn by Noto, smaller and narrower than DejaVu would. Only
# the letters fall through to DejaVu Sans. (An explicit DejaVu family draws everything itself.)
NOTO_LATIN_FIRST, NOTO_LATIN_LAST = 0x20, 0xFF
NOTO_PUNCT_FIRST, NOTO_PUNCT_LAST = 0x2010, 0x2026
ABSENT = 0xFFFF

OUT = pathlib.Path(__file__).resolve().parents[2] / "backend/internal/shorts/render/metrics_gen.go"


def advances(path, first, last, absent=0):
    font = TTFont(path)
    cmap = font.getBestCmap()
    hmtx = font["hmtx"]
    upm = font["head"].unitsPerEm
    out = []
    for cp in range(first, last + 1):
        glyph = cmap.get(cp)
        out.append(absent if glyph is None else math.ceil(hmtx[glyph][0] * 1000 / upm))
    return out


def cell_height(path):
    """libass sizes a font by its cell height, not its em: usWinAscent + usWinDescent, from the OS/2
    table. A caption of ASS size S draws an em of S / cell_height pixels (measured against real
    renders of DejaVu and Noto Devanagari in alpine:3.21, the estimate is within 0.4% of the ink)."""
    font = TTFont(path)
    os2, upm = font["OS/2"], font["head"].unitsPerEm
    return (os2.usWinAscent + os2.usWinDescent) / upm


def fmt(name, values, doc):
    rows = []
    for i in range(0, len(values), 16):
        rows.append("\t" + ", ".join(str(v) for v in values[i : i + 16]) + ",")
    return "// %s\nvar %s = [%d]uint16{\n%s\n}\n" % (doc, name, len(values), "\n".join(rows))


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    folder = pathlib.Path(sys.argv[1])
    parts = [
        "// Code generated by scripts/ops/gen_caption_metrics.py; DO NOT EDIT.\n",
        "package render\n",
        "// Character widths in thousandths of an em, from the fonts in the render images (see the script).\n"
        "// The Latin tables start at U+0020 and end at U+017F. The Devanagari table runs from U+0900 to U+097F.\n"
        "// A zero is a character the font does not have or draws with no advance (a combining mark).\n",
        "const (\n\tlatinFirst = 0x%X\n\tlatinLast  = 0x%X\n\tdevaFirst  = 0x%X\n\tdevaLast   = 0x%X\n)\n" % (LATIN_FIRST, LATIN_LAST, DEVA_FIRST, DEVA_LAST),
        "// Cell height of each font in ems (usWinAscent + usWinDescent): libass makes the ASS font size\n// that many ems tall, so an em is the size divided by this.\n"
        "const (\n\tcellSans      = %.4f\n\tcellSerif     = %.4f\n\tcellCondensed = %.4f\n\tcellDeva      = %.4f\n)\n"
        % (cell_height(folder / "DejaVuSans.ttf"), cell_height(folder / "DejaVuSerif.ttf"), cell_height(folder / "DejaVuSansCondensed.ttf"), cell_height(folder / "NotoSansDevanagari-Regular.ttf")),
        fmt("advSans", advances(folder / "DejaVuSans.ttf", LATIN_FIRST, LATIN_LAST), "DejaVu Sans."),
        fmt("advSerif", advances(folder / "DejaVuSerif.ttf", LATIN_FIRST, LATIN_LAST), "DejaVu Serif."),
        fmt("advCondensed", advances(folder / "DejaVuSansCondensed.ttf", LATIN_FIRST, LATIN_LAST), "DejaVu Sans Condensed."),
        "const (\n\tnotoLatinFirst = 0x%X\n\tnotoLatinLast  = 0x%X\n\tnotoPunctFirst = 0x%X\n\tnotoPunctLast  = 0x%X\n\tnotoAbsent     = 0x%X\n)\n"
        % (NOTO_LATIN_FIRST, NOTO_LATIN_LAST, NOTO_PUNCT_FIRST, NOTO_PUNCT_LAST, ABSENT),
        fmt("advNotoLatin", advances(folder / "NotoSansDevanagari-Regular.ttf", NOTO_LATIN_FIRST, NOTO_LATIN_LAST, ABSENT), "Noto Sans Devanagari, the Latin range (0xFFFF: the font does not have the character)."),
        fmt("advNotoPunct", advances(folder / "NotoSansDevanagari-Regular.ttf", NOTO_PUNCT_FIRST, NOTO_PUNCT_LAST, ABSENT), "Noto Sans Devanagari, general punctuation (quotes, dashes, ellipsis)."),
        fmt("advDeva", advances(folder / "NotoSansDevanagari-Regular.ttf", DEVA_FIRST, DEVA_LAST), "Noto Sans Devanagari, Regular."),
    ]
    OUT.write_text("\n".join(parts))
    print(OUT)


main()
